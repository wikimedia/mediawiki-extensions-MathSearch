<?php
/**
 * Regenerates schema/mathml-mardi.rng from the W3C mathml4-core.rng of
 * https://github.com/w3c/mathml-schema/tree/main/mathml4/rng
 *
 * Each edit must apply exactly once, so a changed core schema stops the script
 * instead of silently producing a different schema.
 *
 * @ingroup Maintenance
 */

use MediaWiki\Maintenance\Maintenance;

// @codeCoverageIgnoreStart
$IP = getenv( 'MW_INSTALL_PATH' );
if ( $IP === false ) {
	$IP = __DIR__ . '/../../..';
}
require_once "$IP/maintenance/Maintenance.php";
// @codeCoverageIgnoreEnd

class BuildMathMLMardi extends Maintenance {

	private const CORE_URL =
		'https://raw.githubusercontent.com/w3c/mathml-schema/main/mathml4/rng/mathml4-core.rng';

	private string $s;

	public function __construct() {
		parent::__construct();
		$this->addDescription( 'Regenerates schema/mathml-mardi.rng from the W3C mathml4-core.rng.' );
		$this->addArg( 'core', 'Path to mathml4-core.rng, downloaded from W3C if the file does not exist' );
		$this->addArg( 'output', 'Output file, defaults to schema/mathml-mardi.rng', false );
	}

	public function execute() {
		$path = $this->getArg( 'core' );
		if ( !file_exists( $path ) ) {
			$this->output( 'Downloading ' . self::CORE_URL . "\n" );
			$core = $this->getServiceContainer()->getHttpRequestFactory()->get( self::CORE_URL, [], __METHOD__ );
			if ( $core === null || file_put_contents( $path, $core ) === false ) {
				$this->fatalError( 'Cannot download ' . self::CORE_URL . " to $path" );
			}
		}
		$core = file_get_contents( $path );
		if ( $core === false ) {
			$this->fatalError( "Cannot read $path" );
		}
		$this->s = $core;
		file_put_contents( $this->getArg( 'output', dirname( __DIR__ ) . '/schema/mathml-mardi.rng' ), $this->build() );
	}

	private function fail( string $message ): never {
		$this->fatalError( $message );
	}

	private function replaceOnce( string $old, string $new ): void {
		if ( substr_count( $this->s, $old ) !== 1 ) {
			$this->fail( "Not found exactly once:\n$old" );
		}
		$this->s = str_replace( $old, $new, $this->s );
	}

	private function replacePatternOnce( string $pattern, string $replacement ): void {
		if ( preg_match_all( $pattern, $this->s ) !== 1 ) {
			$this->fail( "Not found exactly once: $pattern" );
		}
		$this->s = preg_replace( $pattern, $replacement, $this->s );
	}

	private function dropDefine( string $name ): void {
		$this->replacePatternOnce(
			'/  <define name="' . preg_quote( $name, '/' ) . '">\n.*?\n  <\/define>\n/s', '' );
	}

	private static function optionalAttribute( string $name, string $inner = '' ): string {
		if ( $inner === '' ) {
			return "    <optional>\n      <attribute name=\"$name\"/>\n    </optional>\n";
		}
		return "    <optional>\n      <attribute name=\"$name\">\n$inner      </attribute>\n    </optional>\n";
	}

	private function build(): string {
		$this->replaceOnce( <<<'EOT'
<!--
  MathML 4 (Core Level 1)
  #######################
-->
EOT
,
		<<<'EOT'
<!--
  MathML Core plus the epsilon of full MathML 4 that the MaRDI
  portal uses in its MathML statements (property P1455), minus
  the delta of MathML Core that can run script.

  Generated by maintenance/BuildMathMLMardi.php from mathml4-core.rng of
  https://github.com/w3c/mathml-schema/tree/main/mathml4/rng
  The full MathML 4 schema does not compile in libxml, which PHP
  uses to validate.

  Epsilon, from mathml4-presentation.rng, which covers every
  value of P1455 on 2026-11-09:
  * xref on presentation elements
  * rowspacing and columnspacing on mtable
  * menclose

  Delta, which no value of P1455 uses:
  * event handler attributes, autofocus, tabindex and nonce
  * the a element and its link attributes
  * HTML and SVG in token elements
  * elements of other namespaces in annotation-xml, whose
    MathML elements only get the attributes P1455 uses
-->
EOT
		);
		$this->replaceOnce( ' xmlns:svg="http://www.w3.org/2000/svg"', '' );
		foreach ( [ 'MathMLoneventAttributes', 'MathMLlink.attributes', 'a' ] as $name ) {
			$this->dropDefine( $name );
		}
		$this->replaceOnce( "      <ref name=\"a\"/>\n      <ref name=\"mfrac\"/>", '      <ref name="mfrac"/>' );
		$this->replaceOnce( "      <ref name=\"mphantom\"/>\n      <ref name=\"msub\"/>",
			"      <ref name=\"mphantom\"/>\n      <ref name=\"menclose\"/>\n      <ref name=\"msub\"/>" );
		$this->replaceOnce( self::optionalAttribute( 'autofocus', "        <ref name=\"mathml-boolean\"/>\n" ), '' );
		$this->replaceOnce( self::optionalAttribute( 'tabindex', "        <data type=\"integer\"/>\n" ), '' );
		$this->replaceOnce( self::optionalAttribute( 'nonce' ), '' );
		$this->replaceOnce( "    <ref name=\"MathMLoneventAttributes\"/>\n", self::optionalAttribute( 'xref' ) );
		$this->replaceOnce( <<<'EOT'
  <define name="anyElement">
    <element>
      <anyName/>
      <zeroOrMore>
        <choice>
          <attribute>
            <anyName/>
          </attribute>
          <text/>
          <ref name="anyElement"/>
        </choice>
      </zeroOrMore>
    </element>
  </define>
EOT
,
		<<<'EOT'
  <define name="anyElement">
    <element>
      <nsName/>
      <zeroOrMore>
        <choice>
          <attribute name="cd"/>
          <attribute name="closure"/>
          <attribute name="id"/>
          <attribute name="mathsize"/>
          <attribute name="type"/>
          <attribute name="xref"/>
          <text/>
          <ref name="anyElement"/>
        </choice>
      </zeroOrMore>
    </element>
  </define>
EOT
		);
		$textOrHtml = '/(  <define name="textorHTML">\n    <choice>\n      <text\/>\n      <ref name="math"\/>\n)' .
			'.*?(    <\/choice>\n  <\/define>\n)/s';
		$this->replacePatternOnce( $textOrHtml, '$1$2' );
		$spacing = "        <list>\n          <oneOrMore>\n            <ref name=\"length-percentage\"/>\n" .
			"          </oneOrMore>\n        </list>\n";
		$this->replaceOnce(
			"  <define name=\"mtable.attributes\">\n    <ref name=\"MathMLPGlobalAttributes\"/>\n  </define>\n",
			"  <define name=\"mtable.attributes\">\n    <ref name=\"MathMLPGlobalAttributes\"/>\n" .
			self::optionalAttribute( 'rowspacing', $spacing ) . self::optionalAttribute( 'columnspacing', $spacing ) .
			"  </define>\n" );
		$this->replaceOnce( "  <define name=\"msub\">\n", <<<'EOT'
  <define name="menclose">
    <element name="menclose">
      <ref name="menclose.attributes"/>
      <ref name="ImpliedMrow"/>
    </element>
  </define>
  <define name="menclose.attributes">
    <ref name="MathMLPGlobalAttributes"/>

EOT
		. self::optionalAttribute( 'notation' ) . "  </define>\n  <define name=\"msub\">\n" );

		$grammar = substr( $this->s, strpos( $this->s, '<grammar' ) );
		foreach ( [ 'svg', 'xhtml', 'onclick', 'nonce', 'tabindex', 'autofocus', 'href' ] as $word ) {
			if ( str_contains( $grammar, $word ) ) {
				$this->fail( "The schema still contains $word" );
			}
		}
		return $this->s;
	}
}

$maintClass = BuildMathMLMardi::class;
require_once RUN_MAINTENANCE_IF_MAIN;
